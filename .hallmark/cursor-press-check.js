() => {
  const gallery = document.querySelector('.about-services-gallery, .project-images .swiper');
  const swiper = gallery.swiper;
  swiper.params.speed = 0;
  swiper.slideTo(0, 0);
  const rect = gallery.getBoundingClientRect();
  const x = rect.right - 80, y = rect.top + 100;
  const target = document.elementFromPoint(x, y);
  const cursor = document.querySelector('.reference-arrow-cursor');
  const send = (type, buttons = 0, pointerType = 'mouse') => target.dispatchEvent(new PointerEvent(type, {bubbles: true, clientX: x, clientY: y, pointerType, buttons}));
  const assert = (condition, message) => {if (!condition) throw Error(message);};
  send('pointermove');
  assert(cursor.style.display === 'grid', 'Hover shows arrow');
  send('pointerdown', 1);
  assert(cursor.style.display === 'grid' && getComputedStyle(cursor).filter === 'invert(1)', 'Press keeps arrow visible and inverts colors');
  send('pointermove', 1);
  assert(cursor.classList.contains('is-pressed'), 'Movement preserves pressed state');
  send('pointerup');
  assert(cursor.style.display === 'grid' && !cursor.classList.contains('is-pressed'), 'Release restores colors without hiding');
  const before = swiper.realIndex;
  send('click');
  assert(swiper.realIndex !== before && cursor.style.display === 'grid', 'Click navigates without hiding');
  send('pointerdown', 1);
  window.dispatchEvent(new Event('blur'));
  assert(cursor.style.display === 'none' && !cursor.classList.contains('is-pressed'), 'Blur clears pressed state');
  send('pointerdown', 1, 'touch');
  assert(cursor.style.display === 'none', 'No mouse cursor on touch');
  send('pointermove');
  return {route: location.pathname, result: 'passed'};
}